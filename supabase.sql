-- ENCONTRO DE SUPERAÇÕES
-- Execute este arquivo inteiro no SQL Editor do Supabase.

create table if not exists public.relatos (
  id bigint generated by default as identity primary key,
  titulo text not null,
  texto text not null,
  imagem_url text,
  aprovado boolean not null default true,
  criado_em timestamptz not null default now()
);

alter table public.relatos enable row level security;

-- Permissões necessárias para o acesso pelo navegador
grant usage on schema public to anon, authenticated;
grant select, insert on table public.relatos to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

drop policy if exists "relatos_publicos_ler" on public.relatos;
create policy "relatos_publicos_ler"
on public.relatos
for select
to anon, authenticated
using (aprovado = true);

drop policy if exists "relatos_publicos_inserir" on public.relatos;
create policy "relatos_publicos_inserir"
on public.relatos
for insert
to anon, authenticated
with check (
  length(titulo) between 1 and 100
  and length(texto) between 1 and 5000
);

-- Bucket público de fotos
insert into storage.buckets (id, name, public)
values ('fotos', 'fotos', true)
on conflict (id) do update set public = true;

drop policy if exists "fotos_publicas_ver" on storage.objects;
create policy "fotos_publicas_ver"
on storage.objects
for select
to public
using (bucket_id = 'fotos');

drop policy if exists "fotos_publicas_enviar" on storage.objects;
create policy "fotos_publicas_enviar"
on storage.objects
for insert
to anon, authenticated
with check (
  bucket_id = 'fotos'
  and storage.extension(name) = any (array['png','jpg','jpeg','webp','gif'])
);

notify pgrst, 'reload schema';
